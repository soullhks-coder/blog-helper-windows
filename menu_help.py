def attach_heading_help(label, make_button):
    """Group an existing heading without replacing its identity or callbacks.

    Tk grid/pack's `in_` keeps the original widget parent, so references used by
    themes, layout and status updates remain valid. No overlay or polling.
    """
    import customtkinter as ctk
    if getattr(label, "_menu_help_group", None) is not None:
        return None
    manager = label.winfo_manager()
    if manager not in ("grid", "pack"):
        return None
    info = label.grid_info() if manager == "grid" else label.pack_info()
    container = info.pop("in")
    group = ctk.CTkFrame(container, fg_color="transparent", corner_radius=0)
    group._uses_writing_design_theme = True
    if manager == "grid":
        label.grid_forget()
        group.grid(**info)
    else:
        # Preserve pack ordering, including headings followed by packed content.
        siblings = container.pack_slaves()
        next_widget = siblings[siblings.index(label) + 1] if siblings.index(label) + 1 < len(siblings) else None
        label.pack_forget()
        group.pack(**info, **({"before": next_widget} if next_widget is not None else {}))
    label.grid(in_=group, row=0, column=0, sticky="w")
    button = make_button(group)
    button.grid(row=0, column=1, sticky="w")
    # Geometry ownership is not native parentage: the new frame would otherwise
    # cover the older sibling heading on macOS/Windows even though it is mapped.
    label.lift(group)
    label._menu_help_group = group
    button._help_heading = label
    return button
