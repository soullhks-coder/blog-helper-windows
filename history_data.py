def history_dates() -> tuple[str, ...]:
    """Return unique dates in newest-first display order."""

    return tuple(dict.fromkeys(str(entry["date"]) for entry in BLOG_HELPER_HISTORY))


def history_categories() -> tuple[str, ...]:
    """Return sorted unique user-facing categories."""

    return tuple(sorted({str(entry["category"]) for entry in BLOG_HELPER_HISTORY}))


def search_history(
    query: str = "",
    selected_date: str = "전체 날짜",
    selected_category: str = "전체 분류",
) -> list[dict[str, object]]:
    """Filter bundled history across every visible field."""

    normalized_query = " ".join(str(query or "").casefold().split())
    results: list[dict[str, object]] = []
    for entry in BLOG_HELPER_HISTORY:
        if selected_date not in {"", "전체 날짜"} and entry["date"] != selected_date:
            continue
        if selected_category not in {"", "전체 분류"} and entry["category"] != selected_category:
            continue
        searchable = " ".join(
            (
                str(entry["date"]),
                str(entry["version"]),
                str(entry["category"]),
                str(entry["title"]),
                str(entry["request"]),
                " ".join(str(item) for item in entry.get("changes", ())),
            )
        ).casefold()
        if normalized_query and normalized_query not in searchable:
            continue
        results.append(entry)
    return results
